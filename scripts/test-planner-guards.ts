import assert from "node:assert/strict";
import { EnquiryFillGuard, solicitorSummary } from "../lib/agent/plannerGuards";
import { FIXTURE_RESULT } from "../lib/agent/legalAidFixture";
import { CREW, type CrewId, type Say } from "../lib/agent/plannerTypes";
import { stepStatuses } from "../app/case/crew/StepStrip";
import type { CrewState } from "../app/case/usePlannerRun";

const firm = (id: string) => ({ ...FIXTURE_RESULT.firms[0], id, excluded: null, website: "https://example.com", distanceMiles: 2, distanceOrigin: "G1 1XW" });
const guard = new EnquiryFillGuard();
assert.match(guard.claim({ ...firm("a"), excluded: "Defends hospitals" }, ["a"])!, /excluded/);
assert.match(guard.claim(firm("a"), [])!, /Shortlist/);
assert.match(guard.claim(undefined, [])!, /Unknown/);
const claims = ["a", "b", "c", "d"].map((id) => guard.claim(firm(id), ["a", "b", "c", "d"]));
assert.deepEqual(claims.slice(0, 3), [null, null, null]);
assert.match(claims[3]!, /limit/);
assert.match(guard.claim(firm("a"), ["a"])!, /already being filled/);
guard.finish("a", true);
assert.match(guard.claim(firm("a"), ["a"])!, /ready for review/);
const retry = new EnquiryFillGuard();
assert.equal(retry.claim(firm("a"), ["a"]), null);
retry.finish("a", false);
assert.equal(retry.claim(firm("a"), ["a"]), null);
const declined = solicitorSummary([firm("a")], { allowed: false });
assert.doesNotMatch(declined, /Nearest|null miles/);
assert.match(declined, /not shared/);
const near = solicitorSummary([firm("far"), { ...firm("near"), name: "Near firm", distanceMiles: 0.1 }], { allowed: true, postcode: "G1 1XW" });
assert.match(near, /Nearest to G1 1XW: Near firm, 0.1 miles/);
assert.match(solicitorSummary([firm("a")], { allowed: true, postcode: "EH1 1AA" }), /No confirmed distances/);
const crew = Object.fromEntries(Object.keys(CREW).map((id) => [id, { state: "idle", note: "", since: 0 }])) as Record<CrewId, CrewState>;
const failed: Say = { i: 0, t: 0, from: "vera", kind: "report", tool: "check_firm", tab: "Vera - A", ok: false, text: "Could not load the firm" };
assert.equal(stepStatuses(crew, [failed], true)[1], "failed");
assert.equal(stepStatuses(crew, [failed, { ...failed, i: 1, ok: true, text: "Checked" }], true)[1], "done");
assert.equal(stepStatuses(crew, [failed, { ...failed, i: 1, tab: "Vera - B", ok: true, text: "Checked B" }], true)[1], "failed");
assert.equal(stepStatuses(crew, [{ ...failed, ok: undefined, text: "I hit a problem: unavailable" }], true)[1], "failed");
assert.equal(stepStatuses(crew, [], true)[1], "skipped");
console.log("PASS: excluded/unshortlisted guard, concurrent budget, duplicate/retry handling, consent-aware distance summary, failed/recovered progress");
